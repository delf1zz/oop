package ru.nsu.egorov;

/**
 * Перечисление достоинств карт и их базовых значений очков.
 */
public enum Rank {
    /**
     * Двойка (2 очка).
     */
    TWO("Двойка", 2),

    /**
     * Тройка (3 очка).
     */
    THREE("Тройка", 3),

    /**
     * Четверка (4 очка).
     */
    FOUR("Четверка", 4),

    /**
     * Пятерка (5 очков).
     */
    FIVE("Пятерка", 5),

    /**
     * Шестерка (6 очков).
     */
    SIX("Шестерка", 6),

    /**
     * Семерка (7 очков).
     */
    SEVEN("Семерка", 7),

    /**
     * Восьмерка (8 очков).
     */
    EIGHT("Восьмерка", 8),

    /**
     * Девятка (9 очков).
     */
    NINE("Девятка", 9),

    /**
     * Десятка (10 очков).
     */
    TEN("Десятка", 10),

    /**
     * Валет (10 очков).
     */
    JACK("Валет", 10),

    /**
     * Дама (10 очков).
     */
    QUEEN("Дама", 10),

    /**
     * Король (10 очков).
     */
    KING("Король", 10),

    /**
     * Туз (11 очков по умолчанию).
     */
    ACE("Туз", 11);

    private final String name;
    private final int value;

    /**
     * Конструктор достоинства карты.
     *
     * @param name  Название достоинства на русском языке.
     * @param value Числовое значение очков карты.
     */
    Rank(String name, int value) {
        this.name = name;
        this.value = value;
    }

    /**
     * Возвращает название достоинства на русском языке.
     *
     * @return Название достоинства.
     */
    public String getName() {
        return name;
    }

    /**
     * Возвращает базовое числовое значение очков карты.
     *
     * @return Число очков.
     */
    public int getValue() {
        return value;
    }
}